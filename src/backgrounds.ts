/** "amberTide" as "Amber Tide", the name an agent and a menu show. */
const backgroundLabel = (name: string) =>
  name
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/^./, (first) => first.toUpperCase())

